import { copyFileSync, existsSync, mkdirSync } from 'node:fs';
import { fileURLToPath } from 'node:url';
import path from 'node:path';
import { spawnSync } from 'node:child_process';
const root = fileURLToPath(new URL('../../', import.meta.url));
mkdirSync(path.join(root, 'runtime'), { recursive: true });
if (!existsSync(path.join(root, 'runtime/node.exe'))) copyFileSync(process.execPath, path.join(root, 'runtime/node.exe'));
const check = spawnSync(path.join(root, 'runtime/node.exe'), [path.join(root, 'resource-core/providers/sharp/worker.js'), '--check'], { windowsHide: true, encoding: 'utf8' });
if (check.error || check.status !== 0) throw new Error('便携运行时无法加载 Sharp；请在 resource-core 中执行 npm ci：' + (check.error?.message || check.stderr));
copyFileSync(path.join(root, 'desktop/src-tauri/target/release/asset-toolbox.exe'), path.join(root, 'AssetToolbox.exe'));
console.log('已生成 AssetToolbox.exe；移动时请带上 resource-core（含 node_modules）和 runtime。');
